/// Implements paste: save the clipboard → write → synthesize ⌘V → check the landing → restore.
///
/// The text is written with deferred data (NSPasteboardItemDataProvider). This tells us the moment the target app
/// actually reads the clipboard. Restoring only after the read is confirmed makes it less likely that a restore comes too early
/// and the old clipboard content gets pasted. If it is not read and the landing cannot be confirmed either, ⌘V is resent once.
final class Paster: @unchecked Sendable {
    static let shared = Paster()

    private let queue = DispatchQueue(label: "longhand.paste", qos: .userInitiated)

    static let markerTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    func paste(_ p: PastePayload, requestId: String?) {
        let receivedAt = Clock.nowMs()
        queue.async { [self] in run(p, requestId: requestId, receivedAt: receivedAt) }
    }

    private func run(_ p: PastePayload, requestId: String?, receivedAt: Double) {
        let sw = Stopwatch()
        // A new paste ends the previous watch
        FieldWatcher.shared.cancel()
        /// When the first ⌘V was posted (for latency measurement; same clock as hotkey's t)
        var keyPostedAt: Double?
        /// Time spent on AX reads before pasting (checking the target, matching for edit mode, the full text for watching)
        var preReadMs: Double?

        func ack(_ success: Bool, _ reason: String?, landed: String = "unknown", retried: Bool = false) {
            if let reason { Log.info("paste \(p.pasteId) failed: \(reason)") }
            Output.shared.send("paste_ack", id: requestId, PasteAckPayload(
                pasteId: p.pasteId, success: success, failureReason: reason, landed: landed, retried: retried,
                elapsedMs: sw.elapsedMs, keyPostedAt: keyPostedAt.map { ($0 * 1000).rounded() / 1000 },
                keyPostedAfterMs: keyPostedAt.map { (max(0, $0 - receivedAt) * 10).rounded() / 10 },
                preReadMs: preReadMs.map { ($0 * 10).rounded() / 10 }
            ))
        }

        guard AX.isTrusted() else { return ack(false, "not_trusted") }
        let pid = AX.focusedAppPid()
        let bundleId = pid.flatMap { NSRunningApplication(processIdentifier: $0)?.bundleIdentifier }
        if let expect = p.expectBundleId, expect != bundleId {
            Log.info("paste \(p.pasteId): expected \(expect), front is \(bundleId ?? "nil")")
            return ack(false, "app_changed")
        }

        let el = pid.flatMap { AX.focusedElement(appPid: $0) }
        var role: String?
        var secure = false
        if let el {
            let attrs = AX.multiple(el, [kAXRoleAttribute, kAXSubroleAttribute])
            role = attrs[kAXRoleAttribute] as? String
            secure = FieldReader.isSecure(role: role, subrole: attrs[kAXSubroleAttribute] as? String)
            if let role, ContextGatherer.nonTextRoles.contains(role), !AX.isSettable(el, kAXValueAttribute) {
                return ack(false, "no_text_target")
            }
        }

        if let expected = p.expectSelectedText {
            // Edit mode: do not paste unless the selection matches the one recorded (if it cannot be read, treat the target as changed)
            guard let el, !secure else { return ack(false, "edit_target_changed") }
            let current = AX.string(el, kAXSelectedTextAttribute) ?? {
                guard let r = AX.range(el, kAXSelectedTextRangeAttribute), r.length > 0 else { return nil }
                return AX.stringForRange(el, location: r.location, length: r.length)
            }()
            let emptyOK = expected.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
                && (AX.range(el, kAXSelectedTextRangeAttribute)?.length ?? -1) == 0
            guard emptyOK || current.map({ TextSlicing.looselyEqual($0, expected) }) == true else {
                return ack(false, "edit_target_changed")
            }
        }

        let segments = PasteTokenParser.parse(p.text)
        let readable = el != nil && !secure
        let verify = (p.verifyLanding ?? false) && readable
        let watchMs = min(max(0, p.watchMs ?? 0), 600_000)
        // For watching (learning), read the full text and the paste position just before pasting. No watch if it cannot be read
        let beforeSnap = (watchMs > 0 && readable) ? FieldReader.snapshot(el!) : nil
        let inserted = segments.compactMap { seg -> String? in
            if case let .text(t) = seg { return t } else { return nil }
        }.joined()
        preReadMs = Clock.nowMs() - sw.start

        let snapshot = Self.onMain { PasteboardSnapshot.capture() }
        var ownChangeCount: Int?
        var landed = "unknown"
        var retried = false
        var verified = false
        var failure: String?
        var anyRead = false
        // NSPasteboardItem does not hold its data provider strongly, so keep it here until the restore is done
        var keepAlive: [PasteboardProvider] = []

        segmentLoop: for seg in segments {
            switch seg {
            case let .text(text):
                let baseline = (verify && !verified) ? FieldState.read(el!) : nil
                guard let provider = Self.onMain({ Self.writeText(text, markers: p.avoidClipboardHistory ?? true) }) else {
                    failure = "pasteboard_error"
                    break segmentLoop
                }
                ownChangeCount = provider.changeCount
                keepAlive.append(provider)
                let postedAt = KeySynth.pressCommandV()
                if keyPostedAt == nil { keyPostedAt = postedAt }
                if let baseline, baseline.isReadable {
                    var read = provider.waitForRead(timeoutMs: 300)
                    var ok = Self.waitForChange(el!, from: baseline, timeoutMs: read ? 300 : 120)
                    if PasteLanding.shouldResend(changed: ok, read: read) {
                        // The target did not read it, so ⌘V was lost. Resend once
                        Log.info("paste \(p.pasteId): pasteboard not read and field unchanged; resending ⌘V")
                        retried = true
                        KeySynth.pressCommandV()
                        read = provider.waitForRead(timeoutMs: 500)
                        ok = Self.waitForChange(el!, from: baseline, timeoutMs: 300)
                    }
                    anyRead = anyRead || read
                    // Read but no visible change in the field is common in apps with slow AX updates (Electron and others). Do not treat it as a failure
                    landed = PasteLanding.classify(changed: ok, read: read).rawValue
                    if landed == PasteLanding.read.rawValue {
                        Log.info("paste \(p.pasteId): pasteboard was read but the field did not change visibly")
                    }
                    verified = true
                } else {
                    let read = provider.waitForRead(timeoutMs: 800)
                    anyRead = anyRead || read
                    if !read { Log.info("paste \(p.pasteId): pasteboard was not read within 800ms") }
                }
                // Some apps reread several types right after reading, so wait a little
                usleep(40_000)
            case let .key(press):
                KeySynth.press(press)
                usleep(15_000)
            case let .wait(ms):
                usleep(useconds_t(ms) * 1000)
            }
        }

        // Restore: put it back if nobody else wrote after us
        if ownChangeCount != nil {
            Self.onMain {
                let pb = NSPasteboard.general
                if pb.changeCount == ownChangeCount {
                    snapshot.restore(to: pb)
                } else {
                    Log.info("pasteboard changed by someone else; not restoring")
                }
            }
        }

        withExtendedLifetime(keepAlive) {}
        if let failure { return ack(false, failure) }
        if !verify && segments.contains(where: { if case .text = $0 { return true } else { return false } }) {
            landed = "unknown"
        }
        ack(true, nil, landed: landed, retried: retried)
        Log.debug("paste \(p.pasteId): landed=\(landed) retried=\(retried) read=\(anyRead) in \(sw.elapsedMs)ms")

        guard watchMs > 0 else { return }
        if let el, let pid, let snap = beforeSnap {
            let offset = snap.selection.map { max(0, min(snap.text.utf16.count, $0.location - snap.start)) }
            FieldWatcher.shared.start(FieldWatcher.Request(
                pasteId: p.pasteId, element: AXRef(element: el), pid: pid, before: snap.text,
                insertOffset: offset, insertReplacedLength: snap.selection.map { $0.length },
                inserted: inserted, initial: FieldReader.fullText(el), watchMs: watchMs
            ))
        } else {
            FieldWatcher.shared.reportUnreadable(pasteId: p.pasteId, inserted: inserted)
        }
    }

    /// Waits for the field state to change from baseline
    static func waitForChange(_ el: AXUIElement, from baseline: FieldState, timeoutMs: Double) -> Bool {
        let deadline = Clock.nowMs() + timeoutMs
        repeat {
            let now = FieldState.read(el)
            if now.isReadable && now != baseline { return true }
            usleep(30_000)
        } while Clock.nowMs() < deadline
        return false
    }

    // MARK: - Clipboard (call on the main thread)

    private static func writeText(_ text: String, markers: Bool) -> PasteboardProvider? {
        let pb = NSPasteboard.general
        let provider = PasteboardProvider(text: text)
        let item = NSPasteboardItem()
        guard item.setDataProvider(provider, forTypes: [.string]) else { return nil }
        if markers {
            for t in markerTypes { item.setData(Data(), forType: t) }
        }
        pb.clearContents()
        guard pb.writeObjects([item]) else { return nil }
        provider.changeCount = pb.changeCount
        return provider
    }

    static func onMain<T: Sendable>(_ body: @MainActor () -> T) -> T {
        if Thread.isMainThread { return MainActor.assumeIsolated(body) }
        return DispatchQueue.main.sync { MainActor.assumeIsolated(body) }
    }
}

/// Deferred data provider. Signals when the target reads it
final class PasteboardProvider: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    let text: String
    var changeCount = 0
    private let readSignal = DispatchSemaphore(value: 0)
    private let readFlag = LockedValue(false)

    init(text: String) {
        self.text = text
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        if !readFlag.update({ v -> Bool in defer { v = true }; return v }) {
            readSignal.signal()
        }
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}

    /// true once read. Returns at once if it has already been read
    func waitForRead(timeoutMs: Double) -> Bool {
        if readFlag.get() { return true }
        let r = readSignal.wait(timeout: .now() + .milliseconds(Int(timeoutMs)))
        if r == .success { readSignal.signal() } // Put the signal back so the next wait also returns at once
        return r == .success || readFlag.get()
    }
}

/// Saves and restores every item and type on the clipboard
struct PasteboardSnapshot: @unchecked Sendable {
    var items: [[(NSPasteboard.PasteboardType, Data)]] = []

    @MainActor
    static func capture() -> PasteboardSnapshot {
        var snap = PasteboardSnapshot()
        var total = 0
        for item in NSPasteboard.general.pasteboardItems ?? [] {
            var entries: [(NSPasteboard.PasteboardType, Data)] = []
            for t in item.types {
                guard let d = item.data(forType: t) else { continue }
                total += d.count
                entries.append((t, d))
            }
            if !entries.isEmpty { snap.items.append(entries) }
        }
        if total > 64 << 20 { Log.info("pasteboard snapshot is large: \(total >> 20)MB") }
        return snap
    }

    @MainActor
    func restore(to pb: NSPasteboard) {
        pb.clearContents()
        guard !items.isEmpty else { return }
        let objects: [NSPasteboardItem] = items.map { entries in
            let item = NSPasteboardItem()
            for (t, d) in entries { item.setData(d, forType: t) }
            return item
        }
        if !pb.writeObjects(objects) { Log.warn("failed to restore pasteboard") }
    }
}

/// Synthesizes key input. Marks eventSourceUserData so that our own event tap can ignore it
///
/// Posts at the session level. Posting at the HID level sends the event through other apps' HID-level taps queued after it
/// (key remapping tools, for example), which can rewrite ⌘V. The flags are exactly the given modifiers
/// (a held ⌃ or similar is not mixed in).
enum KeySynth {
    /// Presses ⌘V. Returns when the key down was posted (on the Clock.nowMs() base)
    @discardableResult
    static func pressCommandV() -> Double {
        let code = Self.onMainLayoutKeyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        return post(code: code, flags: .maskCommand)
    }

    static func press(_ kp: KeyPress) {
        guard let code = KeyTable.keyCodeByName[kp.key] else { return }
        var flags: CGEventFlags = []
        for m in kp.modifiers { flags.insert(HotkeyEngine.flag(for: m)) }
        post(code: CGKeyCode(code), flags: flags)
    }

    @discardableResult
    static func post(code: CGKeyCode, flags: CGEventFlags) -> Double {
        let src = CGEventSource(stateID: .privateState)
        src?.localEventsSuppressionInterval = 0
        let now = Clock.nowMs()
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: false) else { return now }
        for e in [down, up] {
            e.flags = flags
            e.setIntegerValueField(.eventSourceUserData, value: HotkeyEngine.syntheticMarker)
        }
        let postedAt = Clock.nowMs()
        down.post(tap: .cgSessionEventTap)
        usleep(8_000)
        up.post(tap: .cgSessionEventTap)
        return postedAt
    }

    nonisolated(unsafe) private static var layoutCache: (id: String, map: [Character: CGKeyCode])?

    /// The key code that types the character c with ⌘ held in the current keyboard layout (handles Dvorak and others)
    static func onMainLayoutKeyCode(for c: Character) -> CGKeyCode? {
        Paster.onMain { layoutKeyCode(for: c) }
    }

    @MainActor
    private static func layoutKeyCode(for c: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue() else { return nil }
        let idPtr = TISGetInputSourceProperty(source, kTISPropertyInputSourceID)
        let sourceId = idPtr.map { Unmanaged<CFString>.fromOpaque($0).takeUnretainedValue() as String } ?? "?"
        if let cache = layoutCache, cache.id == sourceId { return cache.map[c] }
        guard let dataPtr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(dataPtr).takeUnretainedValue() as Data
        var map: [Character: CGKeyCode] = [:]
        data.withUnsafeBytes { raw in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return }
            let kbdType = UInt32(LMGetKbdType())
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var len = 0
                let st = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), UInt32((cmdKey >> 8) & 0xFF),
                                        kbdType, OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, chars.count, &len, &chars)
                guard st == noErr, len == 1, let scalar = Unicode.Scalar(chars[0]) else { continue }
                let ch = Character(String(scalar).lowercased())
                if map[ch] == nil { map[ch] = CGKeyCode(code) }
            }
        }
        layoutCache = (sourceId, map)
        return map[c]
    }
}
